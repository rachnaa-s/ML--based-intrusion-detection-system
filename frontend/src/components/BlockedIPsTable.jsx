import React, { useState } from 'react';
import { ShieldBan, Trash2, Plus, Download, AlertTriangle, CheckCircle2, ShieldAlert, Terminal, Lock } from 'lucide-react';

export default function BlockedIPsTable({ blockedIPs = [], onUnblockIP, onBlockIP }) {
  const [manualIP, setManualIP] = useState('');
  const [manualReason, setManualReason] = useState('Manual Tactical SOC Intervention');
  const [inputError, setInputError] = useState('');

  const safeBlocked = Array.isArray(blockedIPs) ? blockedIPs : [];

  const handleManualAdd = (e) => {
    e.preventDefault();
    const trimmed = manualIP.trim();
    if (!trimmed) {
      setInputError('Please enter a valid IPv4 address.');
      return;
    }
    const ipPattern = /^(\d{1,3}\.){3}\d{1,3}$/;
    if (!ipPattern.test(trimmed)) {
      setInputError('Format must be a valid IPv4 (e.g. 198.51.100.45)');
      return;
    }
    if (safeBlocked.some(b => b.ip === trimmed)) {
      setInputError('This IP address is already registered in the perimeter drop table.');
      return;
    }

    setInputError('');
    if (onBlockIP) onBlockIP(trimmed, manualReason);
    setManualIP('');
  };

  const exportRules = () => {
    if (safeBlocked.length === 0) return;
    const ruleText = [
      '# ========================================================',
      '# AEGIS CYBER-SHIELD PERIMETER FIREWALL EXPORT',
      `# GENERATED: ${new Date().toISOString()}`,
      `# ACTIVE DROP RULES: ${safeBlocked.length}`,
      '# ========================================================',
      ...safeBlocked.map(r => `iptables -A INPUT -s ${r.ip} -j DROP # Rule: ${r.id} | Reason: ${r.reason} | Timestamp: ${r.timestamp}`)
    ].join('\n');

    const blob = new Blob([ruleText], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `perimeter_firewall_rules_${new Date().toISOString().slice(0, 10)}.rules`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
  };

  return (
    <div className="hud-corner-card rounded-xl bg-[#060c18] border border-[#152542] overflow-hidden shadow-2xl">
      {/* 1. Header */}
      <div className="p-5 border-b border-[#14233f] flex flex-col sm:flex-row sm:items-center justify-between gap-3 bg-[#040812]">
        <div className="flex items-center gap-3.5">
          <div className="flex items-center justify-center w-10 h-10 rounded-xl bg-rose-950/70 border border-rose-500/50 text-rose-400 shadow-glow-red">
            <ShieldBan className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-base font-bold text-white flex items-center gap-2 font-mono">
              <span>Perimeter Firewall Drop Table (Human Sign-off)</span>
              <span className="text-xs font-mono font-bold text-rose-300 bg-rose-950/70 border border-rose-500/40 px-2.5 py-0.5 rounded">
                {safeBlocked.length} Ingress Drops
              </span>
            </h3>
            <p className="text-xs text-slate-400 mt-0.5 font-sans">
              Human-in-the-loop perimeter drop enforcement generated by intrusion verdicts and analyst directives
            </p>
          </div>
        </div>

        {safeBlocked.length > 0 && (
          <button
            onClick={exportRules}
            className="flex items-center gap-2 px-3.5 py-2 rounded-xl bg-[#0c162d] hover:bg-[#132247] border border-[#1b315b] text-xs font-mono text-cyan-300 hover:text-white transition-all shadow-sm"
          >
            <Download className="w-3.5 h-3.5 text-cyan-400" />
            <span>Export iptables (.rules)</span>
          </button>
        )}
      </div>

      {/* 2. Manual IP Injection Form */}
      <div className="p-4 bg-[#030610] border-b border-[#14233f]">
        <form onSubmit={handleManualAdd} className="flex flex-col sm:flex-row items-stretch sm:items-center gap-3">
          <div className="flex-1">
            <input
              type="text"
              placeholder="IPv4 host address to drop (e.g. 198.51.100.45)..."
              value={manualIP}
              onChange={(e) => { setManualIP(e.target.value); setInputError(''); }}
              className="w-full px-3 py-2 rounded-lg bg-[#081022] border border-[#1a2d4f] text-xs font-mono text-slate-100 placeholder-slate-500 focus:outline-none focus:border-rose-500"
            />
          </div>
          <div className="sm:w-72">
            <input
              type="text"
              placeholder="Military threat justification..."
              value={manualReason}
              onChange={(e) => setManualReason(e.target.value)}
              className="w-full px-3 py-2 rounded-lg bg-[#081022] border border-[#1a2d4f] text-xs font-mono text-slate-200 placeholder-slate-500 focus:outline-none focus:border-rose-500"
            />
          </div>
          <button
            type="submit"
            className="px-5 py-2 rounded-lg bg-rose-600 hover:bg-rose-500 text-white text-xs font-mono font-bold flex items-center justify-center gap-2 shadow-glow-red transition-all"
          >
            <Plus className="w-4 h-4" />
            <span>ENFORCE DROP</span>
          </button>
        </form>
        {inputError && (
          <p className="text-[11px] font-mono text-rose-400 mt-2 flex items-center gap-1.5">
            <AlertTriangle className="w-3.5 h-3.5" />
            {inputError}
          </p>
        )}
      </div>

      {/* 3. Table of Blocked IPs */}
      {safeBlocked.length === 0 ? (
        <div className="p-10 text-center text-xs text-slate-400 font-mono">
          No ingress drops active. When hostile anomalies are detected, deploy an immediate perimeter drop rule.
        </div>
      ) : (
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs font-mono">
            <thead className="bg-[#03060f] text-slate-400 border-b border-[#14233f] uppercase text-[10px] tracking-wider">
              <tr>
                <th className="py-3 px-4">RULE ID</th>
                <th className="py-3 px-4">BLOCKED HOST IP</th>
                <th className="py-3 px-4">THREAT JUSTIFICATION</th>
                <th className="py-3 px-4">FIREWALL STATE</th>
                <th className="py-3 px-4">STAMP</th>
                <th className="py-3 px-4 text-right">ACTION</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-[#0f1b30]">
              {safeBlocked.map((rule) => (
                <tr key={rule.id} className="hover:bg-[#081022]/70 transition-colors">
                  <td className="py-3 px-4 text-cyan-400 font-bold">{rule.id}</td>
                  <td className="py-3 px-4 font-bold text-rose-300 flex items-center gap-2">
                    <ShieldBan className="w-4 h-4 text-rose-500 shrink-0" />
                    <span>{rule.ip}</span>
                  </td>
                  <td className="py-3 px-4 text-slate-300 max-w-xs truncate" title={rule.reason}>
                    {rule.reason}
                  </td>
                  <td className="py-3 px-4">
                    <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-bold bg-rose-950/80 text-rose-300 border border-rose-500/40">
                      DROP (eBPF Active)
                    </span>
                  </td>
                  <td className="py-3 px-4 text-slate-400 text-[11px]">{rule.timestamp}</td>
                  <td className="py-3 px-4 text-right">
                    <button
                      onClick={() => onUnblockIP && onUnblockIP(rule.ip)}
                      className="inline-flex items-center gap-1.5 px-3 py-1 rounded bg-[#200f18] hover:bg-[#341424] text-rose-300 hover:text-white border border-rose-900/50 text-[11px] transition-colors"
                      title="Lift perimeter drop rule"
                    >
                      <Trash2 className="w-3 h-3 text-rose-400" />
                      <span>Lift Drop</span>
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
